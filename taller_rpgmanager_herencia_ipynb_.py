# Crear 3 héroes
heroes = [
    Guerrero("Thorin", 3),
    Mago("Gandalf", 5),
    Arquero("Legolas", 4)
]

# Crear 1 enemigo
orco = Guerrero("Orco", 1)

# ===== FASE 1: EQUIPAR =====
print("=== FASE 1: EQUIPAR ===\n")

for h in heroes:
    if isinstance(h, Equipable):
        if isinstance(h, Guerrero):
            h.equipar_item("Espada Legendaria")
        elif isinstance(h, Arquero):
            h.equipar_item("Arco Elfico")

print("\n=== FASE 2: BATALLA POR TURNOS ===\n")

print("Héroes:")
for h in heroes:
    print(f"  {h}")
print("Enemigo:")
print(f"  {orco}")
print()

# ===== FASE 2: BATALLA =====
turno = 1

while orco.esta_vivo():
    print(f"--- Turno {turno} ---")

    # En el turno 2, usar habilidad especial antes de atacar
    if turno == 2:
        print(">> ¡Habilidades especiales activadas!\n")
        for h in heroes:
            if isinstance(h, Habilidoso):
                h.usar_habilidad_especial(orco)
    else:
        # Turnos normales: ataque básico
        for h in heroes:
            if orco.esta_vivo():
                h.atacar(orco)

    turno += 1

print("\n=== BATALLA TERMINADA ===\n")

# ===== FASE 3: SANACIÓN POST-BATALLA =====
print("=== FASE 3: SANACIÓN POST-BATALLA ===\n")

# Buscar al héroe con menos vida
heroe_con_menos_vida = heroes[0]
for h in heroes:
    if h.puntos_vida < heroe_con_menos_vida.puntos_vida:
        heroe_con_menos_vida = h

# Cada héroe que sea Sanador cura al más herido
for h in heroes:
    if isinstance(h, Sanador):
        h.sanar(heroe_con_menos_vida)

# ===== ESTADO FINAL =====
print("\n=== ESTADO FINAL ===\n")
for h in heroes:
    print(f"  {h}")
print(f"  {orco}")