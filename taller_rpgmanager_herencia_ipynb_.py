from abc import ABC, abstractmethod

class Personaje(ABC):

    def __init__(self, nombre, nivel, vida_max):
        self.nombre = nombre
        self.nivel = nivel
        self.puntos_vida_max = vida_max
        self.puntos_vida = vida_max  # Comienza con vida al máximo

    # Método concreto: recibir daño
    def recibir_dano(self, dano):
        self.puntos_vida -= dano
        if self.puntos_vida < 0:
            self.puntos_vida = 0  # No puede bajar de 0
        print(f"{self.nombre} recibe {dano} de daño. HP: {self.puntos_vida}/{self.puntos_vida_max}")

    # Método concreto: verificar si está vivo
    def esta_vivo(self):
        return self.puntos_vida > 0

    # Métodos abstractos (las subclases DEBEN implementarlos)
    @abstractmethod
    def atacar(self, objetivo):
        pass

    @abstractmethod
    def get_tipo_personaje(self):
        pass

    # Método __str__ (equivalente a toString de Java)
    def __str__(self):
        return f"[{self.get_tipo_personaje()}] {self.nombre} Nv.{self.nivel} | HP: {self.puntos_vida}/{self.puntos_vida_max}"

