from abc import ABC, abstractmethod

# ===== INTERFACES (Clases ABC) =====

class Habilidoso(ABC):

    @abstractmethod
    def usar_habilidad_especial(self, objetivo):
        pass

    @abstractmethod
    def get_costo_habilidad(self):
        pass

    @abstractmethod
    def get_nombre_habilidad(self):
        pass


class Equipable(ABC):

    @abstractmethod
    def equipar_item(self, item):
        pass

    @abstractmethod
    def get_item_equipado(self):
        pass


class Sanador(ABC):

    @abstractmethod
    def sanar(self, objetivo):
        pass

    @abstractmethod
    def get_potencia_sanacion(self):
        pass


# ===== CLASES MODIFICADAS =====

class Guerrero(Personaje, Habilidoso, Equipable):

    def __init__(self, nombre, nivel):
        super().__init__(nombre, nivel, 100 + nivel * 10)
        self.fuerza = 15 + nivel * 3
        self.defensa = 10 + nivel * 2
        self.item_equipado = "Sin equipo"
        self.costo_habilidad = 30

    def atacar(self, objetivo):
        print(f"{self.nombre} (Guerrero) golpea con fuerza {self.fuerza}")
        objetivo.recibir_dano(self.fuerza)

    def get_tipo_personaje(self):
        return "Guerrero"

    def usar_escudo(self):
        print(f"{self.nombre} bloquea con defensa {self.defensa}!")

    # ===== INTERFACE HABILIDOSO =====
    def usar_habilidad_especial(self, objetivo):
        print(f"{self.nombre} usa Golpe Devastador! Daño: 50")
        objetivo.recibir_dano(50)

    def get_costo_habilidad(self):
        return self.costo_habilidad

    def get_nombre_habilidad(self):
        return "Golpe Devastador"

    # ===== INTERFACE EQUIPABLE =====
    def equipar_item(self, item):
        self.item_equipado = item
        print(f"{self.nombre} equipa {item}!")

    def get_item_equipado(self):
        return self.item_equipado


class Mago(Personaje, Habilidoso, Sanador):

    def __init__(self, nombre, nivel):
        super().__init__(nombre, nivel, 60 + nivel * 5)
        self.mana_max = 80 + nivel * 10
        self.mana = self.mana_max

    def atacar(self, objetivo):
        if self.mana >= 20:
            dano = 25 + self.nivel * 5
            print(f"{self.nombre} (Mago) lanza hechizo. Daño: {dano} | Mana: -20")
            objetivo.recibir_dano(dano)
            self.mana -= 20
        else:
            print(f"{self.nombre} (Mago) ¡Mana insuficiente! No puede atacar.")

    def get_tipo_personaje(self):
        return "Mago"

    def recuperar_mana(self, cantidad):
        self.mana += cantidad
        if self.mana > self.mana_max:
            self.mana = self.mana_max
        print(f"{self.nombre} recupera mana. Mana actual: {self.mana}/{self.mana_max}")

    # ===== INTERFACE HABILIDOSO =====
    def usar_habilidad_especial(self, objetivo):
        if self.mana >= 20:
            print(f"{self.nombre} lanza Bola de Fuego! Daño: 40 | Mana: -20")
            objetivo.recibir_dano(40)
            self.mana -= 20
        else:
            print(f"{self.nombre} ¡Mana insuficiente para Bola de Fuego!")

    def get_costo_habilidad(self):
        return 20

    def get_nombre_habilidad(self):
        return "Bola de Fuego"

    # ===== INTERFACE SANADOR =====
    def sanar(self, objetivo):
        print(f"{self.nombre} sana a {objetivo.nombre}. HP restaurado: 25")
        objetivo.puntos_vida += 25
        if objetivo.puntos_vida > objetivo.puntos_vida_max:
            objetivo.puntos_vida = objetivo.puntos_vida_max

    def get_potencia_sanacion(self):
        return 25


class Arquero(Personaje, Equipable):

    def __init__(self, nombre, nivel):
        super().__init__(nombre, nivel, 75 + nivel * 7)
        self.flechas = 10 + nivel * 2
        self.alcance = 30
        self.item_equipado = "Arco basico"

    def atacar(self, objetivo):
        if self.flechas > 0:
            dano = 12 + self.nivel * 4
            # Si tiene un arco mejorado, +5 de daño
